import { randomUUID } from 'node:crypto'
import type { AgentWithConfig, MeetingRow } from './db'
import type { AsyncRepository } from './db/async-repository'
import { CompatibleLLM, type ChatMessage } from './llm/compatible'
import { TOOLS, type ArtifactStore } from './tools'
import { estimateCostUsd } from './pricing'
import { broadcastControl, emit } from './events'

// ─────────────────────────────────────────────────────────────────────────────
// Meeting engine (Phase 4, ARCHITECTURE.md §6 Fase 4). A meeting is a real
// round-robin discussion: every participant speaks through its OWN LLM
// call, with its own persisted config (system prompt, model, temperature)
// and the transcript-so-far as context. Avatars only mirror server truth:
// task.collaboration seats the participants, meeting.speaking marks the
// agent whose turn is actually in flight / just delivered. Speeches stream
// token-by-token (the gateway supports it) and the partial text is pushed
// to the UI as a control frame — real model output as it forms, never a
// typing effect. A failed turn is recorded in the transcript as a system
// entry and the meeting continues; if every turn fails, the meeting is
// marked failed. Minutes (summary + decisions + action items) are
// generated by the organizer and saved as an artifact through the same
// write_document executor the task engine uses.
// ─────────────────────────────────────────────────────────────────────────────

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms))
const now = () => new Date().toISOString()

const MEETING_GUIDANCE =
  '\n\nKonteks: kamu sedang dalam meeting tim yang difasilitasi sistem. Saat giliranmu, ' +
  'berikan kontribusi yang konkret sesuai peranmu: tanggapi poin peserta sebelumnya, ' +
  'jangan mengulanginya. Ringkas: 2–4 kalimat, tanpa pembuka basa-basi, tanpa menyebut ' +
  'bahwa kamu AI. Gunakan bahasa yang dipakai pada topik meeting.'

export class MeetingEngine {
  private current: MeetingRow | null = null

  constructor(
    private repo: AsyncRepository,
    private llm: CompatibleLLM,
    private artifactsDir: string,
    private keyConfigured: boolean,
    // Worker runtime only: minutes/transcript bodies go to this store
    // (D1) instead of the local filesystem. Undefined locally.
    private artifactStore?: ArtifactStore,
  ) {}

  isRunning(): boolean {
    return this.current !== null
  }

  async start(input: { topic: string; participantIds: string[]; rounds: number }): Promise<MeetingRow> {
    if (!this.keyConfigured) {
      throw new Error('KENARI_API_KEY not configured — start the orchestrator via run.py')
    }
    if (this.current) throw new Error('A meeting is already running')
    const meeting: MeetingRow = {
      id: randomUUID(),
      topic: input.topic,
      participantIds: input.participantIds,
      rounds: input.rounds,
      status: 'running',
      artifactFile: null,
      error: null,
      createdAt: now(),
      endedAt: null,
    }
    await this.repo.createMeeting(meeting)
    await this.repo.addActivity('user', 'meeting.started', meeting.id, `"${meeting.topic}" · ${meeting.participantIds.length} agents · ${meeting.rounds} rounds`)
    this.current = meeting
    void this.run(meeting).finally(() => {
      if (this.current?.id === meeting.id) this.current = null
    })
    return meeting
  }

  private async run(meeting: MeetingRow) {
    const participants = (
      await Promise.all(meeting.participantIds.map((id) => this.repo.getAgent(id)))
    ).filter((a): a is AgentWithConfig => a !== null)
    const organizer = participants[0]
    let seq = 0
    let speechCount = 0
    let failureCount = 0
    let currentSpeaker: string | null = null
    const transcript: { name: string; role: string; content: string }[] = []

    // Seat everyone: avatars walk to the HQ meeting room on this event.
    participants.forEach((a, i) => {
      emit('task.collaboration', a.id, meeting.id, { seatIndex: i, meetingId: meeting.id, topic: meeting.topic })
    })

    // Visual keepalive ticker. The frozen §1.3 mapping expires a meeting
    // seat after 45 virtual minutes (≈45 real seconds at 1× speed), and a
    // speaking highlight after 2 — while a real LLM turn takes longer.
    // Re-emitting the SAME true state (participants are in the meeting;
    // this agent's turn is in flight) keeps the mirror honest.
    // Interval is 30 s, measured, not guessed: every task.collaboration
    // makes the frozen sim RE-PLAN the avatar's route, and a cross-campus
    // walk needs ~25 s of uninterrupted walking — at an 8 s interval the
    // participants demonstrably never arrived (walk restarted forever).
    // 30 s is long enough to arrive, short enough to beat the 45-sim-min
    // expiry at the default 1× speed. (At 2×/4× sim speed the expiry burns
    // faster than any safe re-plan interval; the demo meeting has the
    // same property — it never re-emits at all.)
    let lastCollab = Date.now()
    const ticker = setInterval(() => {
      if (Date.now() - lastCollab > 30_000) {
        lastCollab = Date.now()
        participants.forEach((a, i) => {
          emit('task.collaboration', a.id, meeting.id, { seatIndex: i, meetingId: meeting.id, topic: meeting.topic })
        })
      }
      if (currentSpeaker) {
        emit('meeting.speaking', currentSpeaker, meeting.id, { meetingId: meeting.id })
      }
    }, 500)

    try {
      await sleep(6_000) // walk-to-room time, mirroring the task engine's desk walk

      for (let round = 1; round <= meeting.rounds; round++) {
        for (const agent of participants) {
          currentSpeaker = agent.id
          broadcastControl('meeting-turn', { meetingId: meeting.id, agentId: agent.id, round })
          emit('meeting.speaking', agent.id, meeting.id, { meetingId: meeting.id, round })

          const soFar = transcript.length
            ? transcript.map((t) => `${t.name} (${t.role}): ${t.content}`).join('\n')
            : '(Kamu pembicara pertama — buka diskusinya.)'
          const messages: ChatMessage[] = [
            { role: 'system', content: agent.config.systemPrompt + MEETING_GUIDANCE },
            {
              role: 'user',
              content:
                `Topik meeting: ${meeting.topic}\n` +
                `Peserta: ${participants.map((p) => `${p.name} (${p.role})`).join(', ')}.\n` +
                `Putaran ${round} dari ${meeting.rounds}. Transkrip sejauh ini:\n${soFar}\n\n` +
                `Giliranmu berbicara sekarang, sebagai ${agent.name} (${agent.role}).`,
            },
          ]
          try {
            const res = await this.llm.chatStream(messages, {
              temperature: agent.config.temperature,
              model: agent.config.model,
              maxTokens: 2200,
              timeoutMs: 150_000,
              onDelta: (cumulative) =>
                broadcastControl('meeting-delta', { meetingId: meeting.id, agentId: agent.id, text: cumulative }),
            })
            const content = res.content.trim()
            seq += 1
            await this.repo.addMeetingMessage({
              id: randomUUID(), meetingId: meeting.id, seq, agentId: agent.id, kind: 'speech',
              content, tokensIn: res.usage?.prompt_tokens ?? 0,
              tokensOut: res.usage?.completion_tokens ?? 0, createdAt: now(),
            })
            await this.repo.addUsage({
              id: randomUUID(), agentId: agent.id, runId: meeting.id, provider: agent.config.provider,
              model: res.model, tokensIn: res.usage?.prompt_tokens ?? 0,
              tokensOut: res.usage?.completion_tokens ?? 0,
              costUsd: estimateCostUsd(res.usage?.prompt_tokens ?? 0, res.usage?.completion_tokens ?? 0),
              latencyMs: res.latencyMs, createdAt: now(),
            })
            transcript.push({ name: agent.name, role: agent.role, content })
            speechCount += 1
            broadcastControl('meeting-message', { meetingId: meeting.id, agentId: agent.id })
          } catch (err) {
            const message = err instanceof Error ? err.message : String(err)
            failureCount += 1
            seq += 1
            await this.repo.addMeetingMessage({
              id: randomUUID(), meetingId: meeting.id, seq, agentId: agent.id, kind: 'system',
              content: `${agent.name} gagal berbicara pada giliran ini: ${message.slice(0, 200)}`,
              tokensIn: 0, tokensOut: 0, createdAt: now(),
            })
            await this.repo.addActivity('system', 'meeting.turn_failed', meeting.id, `${agent.name}: ${message.slice(0, 140)}`)
            broadcastControl('meeting-message', { meetingId: meeting.id, agentId: agent.id })
          } finally {
            currentSpeaker = null
            broadcastControl('meeting-turn-end', { meetingId: meeting.id, agentId: agent.id })
          }
        }
        // Everyone failed this round → the discussion is not happening.
        if (speechCount === 0 && failureCount > 0) break
      }

      if (speechCount === 0) {
        throw new Error('Every speaking turn failed — no discussion took place')
      }

      // ── Minutes: organizer summarizes; saved via the same artifact path ──
      let artifactFile: string | null = null
      let minutesError: string | null = null
      const transcriptText = transcript.map((t) => `**${t.name} (${t.role}):** ${t.content}`).join('\n\n')
      try {
        // One retry, via the STREAMING call: during verification the
        // non-streaming version of this call failed three times three
        // ways (empty content ×2 while a provider pool was flapping,
        // then a full timeout), while streamed speech calls in the same
        // window succeeded 22 of 24 — bytes flowing keep the gateway's
        // long-response path healthy. Speeches are NOT retried — a failed
        // turn is part of the transcript — but the minutes are a single
        // summary call, so one retry is proportionate. Both failures
        // still land in the honest fallback below, error recorded.
        let res: Awaited<ReturnType<typeof this.llm.chatStream>> | null = null
        let lastErr: unknown = null
        for (let attempt = 1; attempt <= 2 && !res; attempt++) {
          try {
            res = await this.llm.chatStream(
              [
                { role: 'system', content: organizer.config.systemPrompt },
                {
                  role: 'user',
                  content:
                    `Buat notulen meeting dalam markdown dari transkrip berikut. Struktur: ` +
                    `# Notulen — ${meeting.topic}, lalu bagian Ringkasan, Keputusan, dan Action Items ` +
                    `(setiap item: penanggung jawab + tindakannya). Hanya gunakan isi transkrip; ` +
                    `jangan mengarang keputusan yang tidak dibahas.\n\n${transcriptText}`,
                },
              ],
              // 8000, not 3500: the default model is a reasoning model — at
              // 3500 it spent the whole budget on reasoning and returned empty
              // content (same failure the §7 proof hit and fixed at 6000).
              { temperature: 0.4, model: organizer.config.model, maxTokens: 8000, timeoutMs: 150_000 },
            )
          } catch (err) {
            lastErr = err
          }
        }
        if (!res) throw lastErr instanceof Error ? lastErr : new Error(String(lastErr))
        await this.repo.addUsage({
          id: randomUUID(), agentId: organizer.id, runId: meeting.id, provider: organizer.config.provider,
          model: res.model, tokensIn: res.usage?.prompt_tokens ?? 0,
          tokensOut: res.usage?.completion_tokens ?? 0,
          costUsd: estimateCostUsd(res.usage?.prompt_tokens ?? 0, res.usage?.completion_tokens ?? 0),
          latencyMs: res.latencyMs, createdAt: now(),
        })
        const saved = await TOOLS.write_document.execute(
          { title: `Notulen — ${meeting.topic}`, content: res.content },
          { artifactsDir: this.artifactsDir, taskId: meeting.id, store: this.artifactStore },
        )
        if (saved.artifact) {
          artifactFile = saved.artifact.fileName
          await this.repo.addArtifact({
            id: randomUUID(), taskId: meeting.id, runId: meeting.id, agentId: organizer.id,
            kind: 'minutes', title: saved.artifact.title, fileName: saved.artifact.fileName, createdAt: now(),
          })
        }
      } catch (err) {
        // Honest fallback: the artifact is the verbatim transcript, labelled
        // as such — never a summary that was not actually generated.
        minutesError = err instanceof Error ? err.message : String(err)
        const saved = await TOOLS.write_document.execute(
          {
            title: `Transkrip Meeting — ${meeting.topic}`,
            content: `# Transkrip Meeting — ${meeting.topic}\n\n> Ringkasan otomatis gagal dibuat (${minutesError}). Dokumen ini adalah transkrip verbatim.\n\n${transcriptText}\n`,
          },
          { artifactsDir: this.artifactsDir, taskId: meeting.id, store: this.artifactStore },
        )
        if (saved.artifact) {
          artifactFile = saved.artifact.fileName
          await this.repo.addArtifact({
            id: randomUUID(), taskId: meeting.id, runId: meeting.id, agentId: organizer.id,
            kind: 'transcript', title: saved.artifact.title, fileName: saved.artifact.fileName, createdAt: now(),
          })
        }
      }

      await this.repo.updateMeeting(meeting.id, {
        status: 'completed', artifactFile, endedAt: now(),
        error: minutesError ? `Minutes generation failed: ${minutesError}` : null,
      })
      emit('task.completed', organizer.id, meeting.id, {
        artifact: artifactFile ?? '', meetingId: meeting.id, topic: meeting.topic,
      })
      await this.repo.addNotification({
        id: randomUUID(), kind: 'meeting.completed',
        title: `Meeting selesai: ${meeting.topic}`,
        detail: `${speechCount} giliran dari ${participants.length} agent${artifactFile ? ` · ${minutesError ? 'artefak transkrip (notulen otomatis gagal dibuat)' : `notulen: ${artifactFile}`}` : ''}`,
        entityRef: meeting.id, agentId: organizer.id, isRead: false, createdAt: now(),
      })
      broadcastControl('notification', { kind: 'meeting.completed', meetingId: meeting.id })
      await this.repo.addActivity('system', 'meeting.completed', meeting.id, `"${meeting.topic}" · ${speechCount} speeches · ${failureCount} failed turns${artifactFile ? ` · ${artifactFile}` : ''}`)
      broadcastControl('meeting-ended', { meetingId: meeting.id, status: 'completed' })
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err)
      await this.repo.updateMeeting(meeting.id, { status: 'failed', error: message, endedAt: now() })
      if (organizer) {
        emit('task.failed', organizer.id, meeting.id, { error: message.slice(0, 200), meetingId: meeting.id })
      }
      await this.repo.addNotification({
        id: randomUUID(), kind: 'meeting.failed', title: `Meeting gagal: ${meeting.topic}`,
        detail: message.slice(0, 200), entityRef: meeting.id,
        agentId: organizer?.id ?? null, isRead: false, createdAt: now(),
      })
      broadcastControl('notification', { kind: 'meeting.failed', meetingId: meeting.id })
      await this.repo.addActivity('system', 'meeting.failed', meeting.id, `"${meeting.topic}" — ${message.slice(0, 160)}`)
      broadcastControl('meeting-ended', { meetingId: meeting.id, status: 'failed' })
    } finally {
      clearInterval(ticker)
    }
  }
}
